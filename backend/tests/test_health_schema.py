"""Keep Apple Health ORM metadata aligned with the historical database schema."""
import asyncio
from datetime import datetime, timezone
from uuid import uuid4

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
import pytest
from sqlalchemy import UniqueConstraint, select, text
from sqlalchemy.exc import IntegrityError

from app.health.models import AppleHealthToken
from app.identity.models import User


@pytest.mark.asyncio
async def test_migrated_health_schema_has_no_autogenerated_diffs(database_url, session):
    # Normal conftest upgrades this isolated PostgreSQL database to head first.
    config = Config('alembic.ini')
    config.set_main_option('sqlalchemy.url', database_url)
    assert ScriptDirectory.from_config(config).get_heads() == ['0010']
    assert await session.scalar(text('SELECT version_num FROM alembic_version')) == '0010'
    await asyncio.to_thread(command.check, config)


def test_token_metadata_preserves_unique_constraint_and_nonunique_lookup_index():
    table = AppleHealthToken.__table__
    assert any(isinstance(constraint, UniqueConstraint)
               and list(constraint.columns.keys()) == ['token_hash']
               for constraint in table.constraints)
    index, = [index for index in table.indexes
              if index.name == 'ix_apple_health_tokens_token_hash']
    assert list(index.columns.keys()) == ['token_hash']
    assert index.unique is False
    assert table.c.token_hash.nullable is True


@pytest.mark.asyncio
async def test_migrated_tokens_reject_duplicate_hashes_but_allow_multiple_nulls(session):
    users = [User(email=f'{uuid4()}@example.com', password_hash='test-only')
             for _ in range(4)]
    session.add_all(users)
    await session.flush()
    created_at = datetime.now(timezone.utc)
    token_hash = 'a' * 64  # Synthetic hash only, no real token or credential.
    session.add(AppleHealthToken(user_id=users[0].id, token_hash=token_hash,
                                created_at=created_at))
    await session.flush()
    with pytest.raises(IntegrityError):
        async with session.begin_nested():
            session.add(AppleHealthToken(user_id=users[1].id, token_hash=token_hash,
                                        created_at=created_at))
            await session.flush()
    session.add_all([AppleHealthToken(user_id=user.id, token_hash=None,
                                     created_at=created_at) for user in users[2:]])
    await session.flush()
    hashes = (await session.scalars(select(AppleHealthToken.token_hash).where(
        AppleHealthToken.user_id.in_([user.id for user in users])))).all()
    assert hashes.count(token_hash) == 1
    assert hashes.count(None) == 2
